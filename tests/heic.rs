#[test]
fn jpg_to_heic_is_rejected_with_exit_2() {
    // --output-format heic is rejected regardless of the input
    // format (input-only per ADR-0004 § Decision § 5).
    let run = make_run_dir("jpgtog");
    // Copy the HEIC file but rename to .jpg so the batch
    // candidate filter still finds it; the rejection happens at
    // the dispatch layer (not the candidate filter) so the
    // --input-format jpg path is what matters.
    fs::write(run.join("dummy.jpg"), b"not really a jpg").unwrap();
    let out = Command::new(binary())
        .arg(&run)
        .args(["--input-format", "jpg"])
        .args(["--output-format", "heic"])
        .output()
        .expect("spawn binary");
    let _ = fs::remove_dir_all(&run);
    assert_eq!(
        out.status.code(),
        Some(2),
        "--input-format jpg --output-format heic must exit 2"
    );
}

